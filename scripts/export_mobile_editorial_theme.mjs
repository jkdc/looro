import { readFileSync, writeFileSync } from "node:fs";

const path = (relative) => new URL("../" + relative, import.meta.url);
const profiles = JSON.parse(readFileSync(path("shared/design/mobile-theme.json"), "utf8"));
const roles = ["background", "text", "mutedText", "primary", "onPrimary", "sessionSurface", "sessionText", "orbLight", "orbDark"];
if (Object.keys(profiles).join() !== "editorial,reference") throw new Error("Expected editorial and reference profiles.");
for (const [name, profile] of Object.entries(profiles)) {
  if (Object.keys(profile).length !== roles.length + 1 || !["serif", "rounded"].includes(profile.headingStyle) || roles.some((role) => !/^[0-9A-F]{6}$/.test(profile[role] ?? ""))) {
    throw new Error("Invalid color roles in profile: " + name);
  }
}

const android = "apps/android/app/src/main/java/com/jkdc/app/ui/Design.kt";
const ios = "apps/ios/App/Design.swift";
const marker = "// BEGIN GENERATED MOBILE THEME";
const end = "// END GENERATED MOBILE THEME";
for (const [file, swift] of [[android, false], [ios, true]]) {
  const url = path(file);
  const source = readFileSync(url, "utf8");
  const startAt = source.indexOf(marker);
  const endAt = source.indexOf(end);
  if (startAt < 0 || endAt <= startAt) throw new Error("Missing generated theme markers: " + file);
  const lines = [marker, "// swift/kotlin color roles generated by scripts/export_mobile_editorial_theme.mjs"];
  for (const [name, profile] of Object.entries(profiles)) {
    lines.push((swift ? "    static let " : "        val ") + name + " = ConversationPalette(");
    for (const role of roles) {
      const value = (swift ? "themeColor(0x" : "Color(0xFF") + profile[role] + ")";
      lines.push((swift ? "        " : "            ") + role + (swift ? ": " : " = ") + value + ",");
    }
    lines.push((swift ? "        serifHeadline: " : "            serifHeadline = ") + (profile.headingStyle === "serif"));
    lines.push(swift ? "    )" : "        )");
  }
  lines.push(end);
  const updated = source.slice(0, startAt) + lines.join("\n") + source.slice(endAt + end.length);
  if (process.argv.includes("--check")) {
    if (updated !== source) throw new Error("Generated theme is stale: " + file);
  } else if (updated !== source) {
    writeFileSync(url, updated);
  }
}
